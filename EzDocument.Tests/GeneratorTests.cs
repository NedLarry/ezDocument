using Xunit;

namespace EzDocument.Tests;

public sealed class GeneratorTests : IDisposable
{
    private readonly string _root = Directory.CreateTempSubdirectory("ezdoc-tests-").FullName;

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private string Output => Path.Combine(_root, DocumentationGenerator.DefaultOutputFolder);

    private void Write(string relativePath, string content)
    {
        var path = Path.Combine(_root, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private string Read(string relativePath) => File.ReadAllText(Path.Combine(Output, relativePath));

    private const string Controller = """
        using Microsoft.AspNetCore.Mvc;
        namespace Demo;

        public static class R { public const string Base = "api/users"; }
        public enum Role { Admin, Member }
        public class CreateUser { public required string Email { get; set; } public Role Role { get; set; } }

        /// <summary>Manages users.</summary>
        [ApiController]
        [Route(R.Base)]
        public class UsersController : ControllerBase
        {
            [HttpGet("{id:int}")] public IActionResult Get(int id, bool? verbose, CancellationToken ct) => Ok();
            [HttpPost] public IActionResult Create(CreateUser body) => Ok();
            [HttpPut("{id}")] public IActionResult Replace(int id, [FromBody] CreateUser? body, [FromHeader(Name = "X-Tenant")] string tenant) => Ok();
            [HttpGet("~/status")] public IActionResult Status([FromServices] object svc) => Ok();
            public IActionResult NotRouted() => Ok();
        }
        """;

    [Fact]
    public void Documents_controller_routes_bodies_and_parameters()
    {
        Write("Api/Controllers/UsersController.cs", Controller);

        var result = new DocumentationGenerator().Generate(_root, Output);

        Assert.Equal(4, result.EndpointCount);
        var doc = Read("Api/Controllers/UsersController.md");
        Assert.Contains("Manages users.", doc);
        // Constant route resolved, route + query params split, CancellationToken ignored.
        Assert.Contains("| `GET` | `/api/users/{id:int}` | - | route: `id`, query: `verbose?` |", doc);
        Assert.DoesNotContain("`ct`", doc);
        // Complex type inferred as body under [ApiController].
        Assert.Contains("| `POST` | `/api/users` | **Required** `CreateUser` | - |", doc);
        // Nullable explicit body is optional; header name override honoured.
        Assert.Contains("| `PUT` | `/api/users/{id}` | Optional `CreateUser?` | route: `id`, header: `X-Tenant` |", doc);
        // ~/ overrides the controller prefix; [FromServices] excluded.
        Assert.Contains("| `GET` | `/status` | - | - |", doc);
        Assert.DoesNotContain("NotRouted", doc);
        // DTO fields, required keyword, enum values and JSON example.
        Assert.Contains("| `email` | `string` | Yes |", doc);
        Assert.Contains("One of: `Admin`, `Member`", doc);
        Assert.Contains("\"email\": \"string\"", doc);
    }

    [Fact]
    public void Documents_minimal_apis_with_group_prefixes()
    {
        Write("Program.cs", """
            var app = WebApplication.Create();
            var api = app.MapGroup("/api").RequireAuthorization();
            var todos = api.MapGroup("todos");
            todos.MapGet("/{id}", (int id, string? q) => Results.Ok());
            todos.MapPost("/", (Todo todo) => Results.Ok()).AllowAnonymous();
            app.MapGet("/health", () => "ok");
            record Todo(string Title, bool Done = false);
            """);

        var result = new DocumentationGenerator().Generate(_root, Output);

        Assert.Equal(3, result.EndpointCount);
        var doc = Read("Program.endpoints.md");
        Assert.Contains("| `GET` | `/api/todos/{id}` | - | route: `id`, query: `q?` | Required |", doc);
        Assert.Contains("| `POST` | `/api/todos` | **Required** `Todo` | - | - |", doc);
        Assert.Contains("| `GET` | `/health` | - | - | - |", doc);
        Assert.Contains("| `title` | `string` | Yes |", doc);
        Assert.Contains("| `done` | `bool` | No |", doc);
    }

    [Fact]
    public void Output_folder_ignores_itself_and_is_not_rescanned()
    {
        Write("UsersController.cs", Controller);

        new DocumentationGenerator().Generate(_root, Output);
        // A .cs file inside the output folder must never be scanned.
        File.WriteAllText(Path.Combine(Output, "Stray.cs"), "[ApiController] public class StrayController { [HttpGet(\"x\")] public void X() {} }");
        var second = new DocumentationGenerator().Generate(_root, Output);

        Assert.Equal("# Generated by EzDocument: keep generated API docs out of source control.\n*\n", File.ReadAllText(Path.Combine(Output, ".gitignore")));
        Assert.Equal(4, second.EndpointCount);
        Assert.Contains("README.md", second.Files);
    }

    [Fact]
    public void Rerun_removes_stale_docs_but_keeps_foreign_files()
    {
        Write("A/OldController.cs", "[ApiController][Route(\"old\")] public class OldController { [HttpGet] public void Get() {} }");
        new DocumentationGenerator().Generate(_root, Output);
        Assert.True(File.Exists(Path.Combine(Output, "A", "OldController.md")));

        File.Delete(Path.Combine(_root, "A", "OldController.cs"));
        File.WriteAllText(Path.Combine(Output, "notes.txt"), "mine");
        new DocumentationGenerator().Generate(_root, Output);

        Assert.False(Directory.Exists(Path.Combine(Output, "A")));
        Assert.True(File.Exists(Path.Combine(Output, "notes.txt")));
    }

    [Fact]
    public void Refuses_to_write_into_a_foreign_non_empty_folder_without_force()
    {
        var foreign = Path.Combine(_root, "docs");
        Directory.CreateDirectory(foreign);
        File.WriteAllText(Path.Combine(foreign, "handbook.md"), "hand written");

        Assert.Throws<IOException>(() => new DocumentationGenerator().Generate(_root, foreign));

        new DocumentationGenerator().Generate(_root, foreign, force: true);
        Assert.Equal("hand written", File.ReadAllText(Path.Combine(foreign, "handbook.md")));
    }

    [Fact]
    public void Sample_api_end_to_end()
    {
        var sample = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../samples/SampleApi"));
        var output = Path.Combine(_root, "sample-docs");

        var result = new DocumentationGenerator().Generate(sample, output);

        Assert.Equal(13, result.EndpointCount);
        var index = File.ReadAllText(Path.Combine(output, "README.md"));
        Assert.Contains("- **5** require a request body", index);
        Assert.Contains("| `POST` | `/api/v1/orders` | **Required** `CreateOrderRequest` | header: `Idempotency-Key` | Required |", index);
        Assert.Contains("| `GET` | `/api/v1/products` | - | query: `search?`, query: `page?` | - |", index);
        Assert.Contains("| `POST` | `/api/v1/orders/{id:guid}/invoice` | **Required** form | route: `id` | Required |", index);
    }
}
