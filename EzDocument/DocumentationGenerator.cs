using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace EzDocument;

public sealed record GenerationResult(string OutputDirectory, int GroupCount, int EndpointCount, IReadOnlyList<string> Files);

/// <summary>
/// Traverses a source tree, discovers ASP.NET Core endpoints (controllers and minimal APIs)
/// and writes Markdown documentation into a git-ignored output directory.
/// </summary>
public sealed class DocumentationGenerator
{
    public const string DefaultOutputFolder = "api-docs";
    internal const string ManifestFileName = ".ezdocument";

    private static readonly HashSet<string> SkippedDirectories = new(StringComparer.OrdinalIgnoreCase)
    {
        "bin", "obj", ".git", ".vs", ".vscode", ".idea", "node_modules", "packages", "TestResults", "artifacts"
    };

    private static readonly UTF8Encoding Utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    public GenerationResult Generate(string sourceDirectory, string outputDirectory, bool force = false)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(sourceDirectory);
        ArgumentException.ThrowIfNullOrWhiteSpace(outputDirectory);

        var root = Path.GetFullPath(sourceDirectory);
        if (!Directory.Exists(root))
        {
            throw new DirectoryNotFoundException($"Source directory does not exist: {root}");
        }

        var output = Path.GetFullPath(outputDirectory);
        PrepareOutputDirectory(output, force);

        var files = EnumerateSourceFiles(root, output)
            .Select(path => new SourceFile(
                Path.GetRelativePath(root, path),
                CSharpSyntaxTree.ParseText(File.ReadAllText(path), path: path).GetCompilationUnitRoot()))
            .ToList();

        var index = new SourceIndex(files);
        var controllers = new ControllerScanner(index);
        var minimalApis = new MinimalApiScanner(index);

        var groups = new List<EndpointGroup>();
        foreach (var file in files)
        {
            groups.AddRange(controllers.Scan(file));
            if (minimalApis.Scan(file) is { } minimal)
            {
                groups.Add(minimal);
            }
        }

        var written = new List<string>();
        var links = new List<(EndpointGroup, string)>();
        var usedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "README.md" };
        foreach (var group in groups)
        {
            var relative = UniquePath(OutputPath(group), usedPaths);
            var target = Path.Combine(output, relative);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllText(target, MarkdownRenderer.RenderGroup(group), Utf8NoBom);
            written.Add(relative);
            links.Add((group, relative.Replace(Path.DirectorySeparatorChar, '/')));
        }

        File.WriteAllText(Path.Combine(output, "README.md"), MarkdownRenderer.RenderIndex(links, Path.GetFileName(root)), Utf8NoBom);
        written.Insert(0, "README.md");

        File.WriteAllLines(Path.Combine(output, ManifestFileName), written.Prepend("# Files generated by EzDocument. Safe to delete this folder."), Utf8NoBom);

        return new GenerationResult(output, groups.Count, groups.Sum(g => g.Endpoints.Count), written);
    }

    /// <summary>
    /// Creates the output folder and makes it ignore itself (a .gitignore containing "*"),
    /// so the documentation is never committed regardless of the host repository's .gitignore.
    /// Files from a previous run are removed using the manifest; foreign files are never deleted.
    /// </summary>
    private static void PrepareOutputDirectory(string output, bool force)
    {
        var manifest = Path.Combine(output, ManifestFileName);
        if (Directory.Exists(output))
        {
            if (File.Exists(manifest))
            {
                foreach (var line in File.ReadAllLines(manifest).Where(l => l.Length > 0 && !l.StartsWith('#')))
                {
                    var previous = Path.GetFullPath(Path.Combine(output, line));
                    if (IsWithin(previous, output) && File.Exists(previous))
                    {
                        File.Delete(previous);
                    }
                }

                DeleteEmptyDirectories(output);
            }
            else if (Directory.EnumerateFileSystemEntries(output).Any() && !force)
            {
                throw new IOException(
                    $"Output directory '{output}' already contains files that were not generated by EzDocument. " +
                    "Choose another --output directory or pass --force to write into it anyway.");
            }
        }

        Directory.CreateDirectory(output);
        var gitignore = Path.Combine(output, ".gitignore");
        if (!File.Exists(gitignore))
        {
            File.WriteAllText(gitignore, "# Generated by EzDocument: keep generated API docs out of source control.\n*\n", Utf8NoBom);
        }
    }

    private static IEnumerable<string> EnumerateSourceFiles(string root, string output)
    {
        var pending = new Stack<string>();
        pending.Push(root);
        var results = new List<string>();
        while (pending.Count > 0)
        {
            var directory = pending.Pop();
            IEnumerable<string> subdirectories;
            try
            {
                results.AddRange(Directory.EnumerateFiles(directory, "*.cs")
                    .Where(file => !file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
                                   && !file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)));
                subdirectories = Directory.EnumerateDirectories(directory);
            }
            catch (UnauthorizedAccessException)
            {
                continue;
            }

            foreach (var subdirectory in subdirectories)
            {
                var name = Path.GetFileName(subdirectory);
                var info = new DirectoryInfo(subdirectory);
                if (SkippedDirectories.Contains(name)
                    || info.Attributes.HasFlag(FileAttributes.ReparsePoint)
                    || string.Equals(Path.GetFullPath(subdirectory), output, StringComparison.Ordinal)
                    || File.Exists(Path.Combine(subdirectory, ManifestFileName)))
                {
                    continue;
                }

                pending.Push(subdirectory);
            }
        }

        return results.OrderBy(file => file, StringComparer.Ordinal);
    }

    private static string OutputPath(EndpointGroup group)
    {
        var directory = Path.GetDirectoryName(group.SourcePath) ?? string.Empty;
        var fileName = Path.GetFileNameWithoutExtension(group.SourcePath);
        var name = group.Kind == EndpointGroupKind.MinimalApi
            ? $"{fileName}.endpoints.md"
            : fileName.Equals(group.Name, StringComparison.OrdinalIgnoreCase) ? $"{group.Name}.md" : $"{fileName}-{group.Name}.md";
        return Path.Combine(directory, name);
    }

    private static string UniquePath(string path, HashSet<string> used)
    {
        var candidate = path;
        for (var i = 2; !used.Add(candidate); i++)
        {
            candidate = Path.Combine(Path.GetDirectoryName(path) ?? string.Empty, $"{Path.GetFileNameWithoutExtension(path)}-{i}.md");
        }

        return candidate;
    }

    private static bool IsWithin(string path, string directory)
    {
        var relative = Path.GetRelativePath(directory, path);
        return relative != ".." && !relative.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal) && !Path.IsPathRooted(relative);
    }

    private static void DeleteEmptyDirectories(string directory)
    {
        foreach (var child in Directory.EnumerateDirectories(directory))
        {
            DeleteEmptyDirectories(child);
            if (!Directory.EnumerateFileSystemEntries(child).Any())
            {
                Directory.Delete(child);
            }
        }
    }
}
